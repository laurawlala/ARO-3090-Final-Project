% Extract_Porkchop_Candidates.m
% Run the profs ARO3090_Porkchop_Plots.m first
clc;

% EDITABLE
C3_vehicle_max = 136.67;   % [km^2/s^2] launch-vehicle limit
C3_vehicle_min = 0;        % [km^2/s^2]

% Optional TOF limits for filtering candidates
TOF_filter_min = 0;         % [days]
TOF_filter_max = inf;       % [days]

numberToDisplay = 30;
outputFile = 'Porkchop_Candidates.mat';
outputTable = 'Porkchop_Candidates.csv';

%% CHECK THAT THE PORKCHOP SCRIPT HAS ALREADY RUN
requiredVariables = {'C3_dep','C3_arr','JD_Dep','JD_Arr', ...
    'TOF','vinf_dep_vec','vinf_arr_vec'};

for k = 1:length(requiredVariables)
    if ~evalin('base',sprintf('exist(''%s'',''var'')',requiredVariables{k}))
        error(['Missing variable: ',requiredVariables{k}, ...
            '. Run ARO3090_Porkchop_Plots.m first.'])
    end
end

% Read results from the base workspace
C3_dep = evalin('base','C3_dep');
C3_arr = evalin('base','C3_arr');
JD_Dep = evalin('base','JD_Dep');
JD_Arr = evalin('base','JD_Arr');
TOF = evalin('base','TOF');
vinf_dep_vec = evalin('base','vinf_dep_vec');
vinf_arr_vec = evalin('base','vinf_arr_vec');

% FIND VALID TRANSFERS
% Expand the TOF condition across all launch dates
valid = (C3_dep >= C3_vehicle_min) & ...
        (C3_dep <= C3_vehicle_max) & ...
        (repmat(TOF(:),1,size(C3_dep,2)) >= TOF_filter_min) & ...
        (repmat(TOF(:),1,size(C3_dep,2)) <= TOF_filter_max) & ...
        isfinite(C3_dep);

[tofIndex,launchIndex] = find(valid);
linearIndex = sub2ind(size(C3_dep),tofIndex,launchIndex);

if isempty(linearIndex)
    error('No transfers satisfy the selected C3 and TOF limits.')
end

% CANDIDATE TABLE
launchJD = JD_Dep(launchIndex)';
arrivalJD = JD_Arr(linearIndex);

candidateTable = table( ...
    (1:length(linearIndex))', ...
    launchIndex, ...
    tofIndex, ...
    datetime(launchJD,'ConvertFrom','juliandate'), ...
    TOF(tofIndex)', ...
    datetime(arrivalJD,'ConvertFrom','juliandate'), ...
    C3_dep(linearIndex), ...
    sqrt(C3_dep(linearIndex)), ...
    C3_arr(linearIndex), ...
    sqrt(C3_arr(linearIndex)), ...
    'VariableNames',{ ...
    'CandidateNumber', ...
    'LaunchIndex', ...
    'TOFIndex', ...
    'LaunchDate', ...
    'TOF_days', ...
    'ArrivalDate', ...
    'C3_departure', ...
    'Vinf_departure', ...
    'C3_arrival', ...
    'Vinf_arrival'});

% Sort by departure C3 first, then by TOF
candidateTable = sortrows(candidateTable, ...
    {'C3_departure','TOF_days'});

% DISPLAY RESULTS
fprintf('\nValid transfer candidates found: %d\n',height(candidateTable))
fprintf('Showing the best %d candidates:\n\n', ...
    min(numberToDisplay,height(candidateTable)))
disp(candidateTable(1:min(numberToDisplay,height(candidateTable)),:))

% SAVE VECTORS FOR LATER
% The first-leg incoming flyby vector is vinf_arr_vec.
% The first-leg Earth departure vector is vinf_dep_vec.

numberToSave = height(candidateTable);
Candidate = repmat(struct( ...
    'LaunchDate',[], ...
    'TOF_days',[], ...
    'ArrivalDate',[], ...
    'C3_departure',[], ...
    'C3_arrival',[], ...
    'vinf_departure_vec',[], ...
    'vinf_arrival_vec',[]),numberToSave,1);

for k = 1:numberToSave
    i = candidateTable.TOFIndex(k);
    j = candidateTable.LaunchIndex(k);

    Candidate(k).LaunchDate = candidateTable.LaunchDate(k);
    Candidate(k).TOF_days = candidateTable.TOF_days(k);
    Candidate(k).ArrivalDate = candidateTable.ArrivalDate(k);
    Candidate(k).C3_dep = candidateTable.C3_departure(k);
    Candidate(k).C3_arr = candidateTable.C3_arrival(k);
    Candidate(k).vinf_dep_vec = vinf_dep_vec(:,i,j);
    Candidate(k).vinf_arr_vec = vinf_arr_vec(:,i,j);
end

save(outputFile,'candidateTable','Candidate')
writetable(candidateTable,outputTable)

fprintf('\nSaved candidate data to:\n%s\n%s\n',outputFile,outputTable)
fprintf(['For the first leg, use Candidate(k).vinf_arrival_vec as the ', ...
    'incoming flyby vector.\n'])
